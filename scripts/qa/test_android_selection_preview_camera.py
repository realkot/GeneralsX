OUT.mkdir(parents=True,exist_ok=True)
def function(text,signature):
 start=text.index(signature);brace=text.index('{',start)
 clean=re.sub(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"',lambda m:' '*len(m.group()),text)
 depth=1;end=brace+1
 while depth:
  depth+=(clean[end]=='{')-(clean[end]=='}');end+=1
 return text[start:end]
def run(name,code):
 p=OUT/(name+'.cpp');p.write_text(code)
 exe=OUT/name
 subprocess.run(['c++','-std=c++17','-Wall','-Wextra','-Werror=return-type',str(p),'-o',str(exe)],check=True)
 subprocess.run([str(exe)],check=True)
